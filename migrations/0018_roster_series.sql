-- Recurring shift series metadata.
--
-- Recurrence is computed by the client in local wall time and submitted as an
-- atomic batch, so the server never has to guess a timezone. These columns keep
-- every generated shift tied to the same series and carry the human label that
-- the client used (daily, weekly, fortnightly, ...).

ALTER TABLE shifts
    ADD COLUMN series_id  uuid,
    ADD COLUMN recurrence text;

CREATE INDEX shifts_series_idx
    ON shifts (organisation_id, series_id)
    WHERE series_id IS NOT NULL;

COMMENT ON COLUMN shifts.series_id IS
    'Shared identifier for shifts generated by one recurrence. NULL for standalone shifts.';
COMMENT ON COLUMN shifts.recurrence IS
    'Human-readable recurrence label supplied by the client, e.g. weekly or fortnightly. NULL for standalone shifts.';
